/**
 * Sends the group ranks to the next stages (e.g. 1st and 2nd → Élite, 3rd and 4th → Amateur); a tie between teams
 * going to different stages is settled here by moving a team up in its group.
 */
function Qualify({ stage: s, stages, action }: { stage: OverviewStage; stages: OverviewStage[]; action: Action }) {
  const targets = stages.filter((x) => x.id !== s.id && x.order > s.order);
  const navigate = useNavigate();
  const { tournamentId } = useParams();
  const [rules, setRules] = useState<{ ranks: string; target: string }[]>(() => {
    const size = Math.min(...s.groups.map((g) => g.standings.length));
    if (targets.length >= 2 && size >= 2) {
      const half = Math.ceil(size / 2);
      return [
        { ranks: range(1, half).join(','), target: targets[0].id },
        { ranks: range(half + 1, size).join(','), target: targets[1].id },
      ];
    }
    return [{ ranks: '1,2', target: targets[0]?.id ?? '' }];
  });
  // a group where nothing was played is not "tied": its order is the seeds
  const tiedGroups = s.groups.filter((g) => g.standings.some((r) => r.tied && r.played > 0) && g.id);
  const [orders, setOrders] = useState<Record<string, string[]>>({});
  if (!targets.length) return <p className="text-sm text-muted">Créez la phase suivante (arbre) pour y qualifier des équipes.</p>;
  const parsed = rules.map((r) => ({
    ranks: r.ranks
      .split(/[^\d]+/)
      .filter(Boolean)
      .map(Number),
    targetStageId: r.target,
  }));
  const valid = parsed.every((r) => r.ranks.length && r.targetStageId);
  return (
    <form
      className="space-y-3 border-l-2 border-line-strong pl-4"
      onSubmit={async (e: FormEvent) => {
        e.preventDefault();
        const done = await action.run('Équipes qualifiées, arbres générés', () =>
          api(`/api/tournament/stages/${s.id}/qualify`, {
            method: 'POST',
            // the order shown for a tied group is the one decided (moved or left as is)
            body: JSON.stringify({
              rules: parsed,
              manualOrder: tiedGroups.length
                ? Object.fromEntries(tiedGroups.map((g) => [g.id!, orders[g.id!] ?? g.standings.map((r) => r.teamId!)]))
                : undefined,
            }),
          }),
        );
        // on to the first bracket: its matches are ready
        if (done && parsed[0]) navigate(tournamentPath(tournamentId ?? '', `matchs/${parsed[0].targetStageId}`));
      }}
    >
      <h4 className="text-sm font-semibold text-text">Qualification</h4>
      {rules.map((r, i) => (
        <div key={i} className="flex flex-wrap items-end gap-2">
          <Field label="Places dans chaque poule">
            <Input
              value={r.ranks}
              onChange={(e) => setRules(rules.map((x, j) => (j === i ? { ...x, ranks: e.target.value } : x)))}
              className="w-24 font-mono"
              placeholder="1,2"
            />
          </Field>
          <Field label="vont en">
            <Select value={r.target} onChange={(e) => setRules(rules.map((x, j) => (j === i ? { ...x, target: e.target.value } : x)))}>
              <option value="">choisir</option>
              {targets.map((t) => (
                <option key={t.id} value={t.id}>
                  {t.name}
                </option>
              ))}
            </Select>
          </Field>
          {rules.length > 1 && (
            <Button small onClick={() => setRules(rules.filter((_, j) => j !== i))}>
              Retirer
            </Button>
          )}
        </div>
      ))}
      <Button small onClick={() => setRules([...rules, { ranks: '', target: '' }])}>
        Ajouter une règle
      </Button>
      {tiedGroups.map((g) => {
        const order = orders[g.id!] ?? g.standings.map((r) => r.teamId!);
        const name = (id: string) => g.standings.find((r) => r.teamId === id)?.team ?? id;
        return (
          <div key={g.id} className="space-y-1">
            <p className="text-sm text-pause">Poule {g.name} : égalité. Ordre retenu pour la qualification :</p>
            <ol className="space-y-1">
              {order.map((id, i) => (
                <li key={id} className="flex items-center gap-2 text-sm">
                  <span className="w-6 text-right font-mono text-muted">{i + 1}</span>
                  <span className="min-w-40 text-white">{name(id)}</span>
                  <Button
                    small
                    disabled={i === 0}
                    onClick={() => {
                      const next = [...order];
                      [next[i - 1], next[i]] = [next[i], next[i - 1]];
                      setOrders({ ...orders, [g.id!]: next });
                    }}
                  >
                    Monter
                  </Button>
                </li>
              ))}
            </ol>
          </div>
        );
      })}
      <Button primary type="submit" disabled={action.busy || !valid}>
        Qualifier
      </Button>
    </form>
  );
}

/** One format for every match not started of the stage, or of one of its brackets (the tournament runs late). */
function StageFormat({ stage: s, action }: { stage: OverviewStage; action: Action }) {
  // a bracket of 2 teams is a plain final (no map advantage): a BO1 is allowed there
  const duel = s.type === 'DOUBLE_ELIM' && s.matches.length === 1;
  const [scope, setScope] = useState('');
  const [format, setFormat] = useState('BO1');
  return (
    <form
      className="flex flex-wrap items-end gap-2"
      onSubmit={(e: FormEvent) => {
        e.preventDefault();
        action.run(`Format ${format} appliqué aux matchs pas commencés`, () =>
          api('/api/tournament/matches/format', { method: 'POST', body: JSON.stringify({ stageId: s.id, bracket: scope || undefined, format }) }),
        );
      }}
    >
      <Field label="Changer le format de">
        <Select
          value={scope}
          onChange={(e) => {
            setScope(e.target.value);
            if (e.target.value === 'FINAL' && format === 'BO1' && !duel) setFormat('BO3'); // never a BO1 grand final
          }}
        >
          <option value="">toute la phase</option>
          {s.type === 'DOUBLE_ELIM' && (
            <>
              <option value="UPPER">bracket du haut</option>
              <option value="LOWER">bracket du bas</option>
              <option value="FINAL">grande finale</option>
            </>
          )}
        </Select>
      </Field>
      <Field label="en">
        <FormatSelect value={format} onChange={setFormat} noBo1={scope === 'FINAL' && !duel} />
      </Field>
      <Button small type="submit" disabled={action.busy}>
        Appliquer
      </Button>
    </form>
  );
}

function FormatSelect({ value, onChange, noBo1 = false }: { value: string; onChange: (v: string) => void; noBo1?: boolean }) {
  return (
    <Select value={value} onChange={(e) => onChange(e.target.value)}>
      {!noBo1 && <option>BO1</option>}
      <option>BO3</option>
      <option>BO5</option>
    </Select>
  );
}

/**
 * "À faire maintenant" (asked by the user: after the groups, what next was unclear): what the tournament waits for,
 * with the button to it. Stages run in order; brackets fed by the same groups run side by side. "Tournoi terminé"
 * only when every stage is played; a bracket that cannot be played (fewer than 2 teams) says why.
 */
export function NextAction({ tournamentId, stages }: { tournamentId: string; stages: OverviewStage[] }) {
  const base = tournamentPath(tournamentId);
  const items: { text: string; to?: string; label?: string; tone?: 'ok' | 'pause' }[] = [];
  const plural = (n: number) => `${n} match${n > 1 ? 's' : ''} à jouer`;
  let blocked = false;
  if (!stages.length) items.push({ text: 'Aucune phase.', to: `${base}/phases`, label: 'Créer les phases' });
  for (const s of stages) {
    const n = matchesLeft(s);
    if (s.type === 'ROUND_ROBIN') {
      const later = stages.filter((x) => x.order > s.order);
      if (!isGenerated(s)) {
        items.push({ text: `${s.name} pas encore générées.`, to: `${base}/matchs/${s.id}`, label: `Générer ${s.name}` });
        blocked = true;
        break;
      }
      if (n) {
        items.push({ text: `${s.name} en cours : ${plural(n)}.`, to: `${base}/matchs/${s.id}`, label: 'Voir les matchs', tone: 'ok' });
        blocked = true;
        break;
      }
      if (later.length && !later.some((x) => x.participants?.length)) {
        items.push({ text: `${s.name} finies.`, to: `${base}/matchs/qualification-${s.id}`, label: 'Qualifier les équipes', tone: 'pause' });
        blocked = true;
        break;
      }
      continue;
    }
    const teams = s.participants?.length ?? 0;
    if (!isGenerated(s)) {
      blocked = true;
      if (teams >= 2)
        items.push({ text: `${s.name} : ${teams} équipes qualifiées, arbre pas encore généré.`, to: `${base}/matchs/${s.id}`, label: `Générer ${s.name}` });
      else
        items.push({
          text: `${s.name} : ${teams ? 'une seule équipe qualifiée' : 'aucune équipe qualifiée'}, il en faut au moins 2 pour un arbre. Revoir la qualification ou supprimer la phase.`,
          to: `${base}/phases`,
          label: 'Phases',
          tone: 'pause',
        });
      continue;
    }
    if (n) {
      blocked = true;
      items.push({ text: `${s.name} en cours : ${plural(n)}.`, to: `${base}/matchs/${s.id}`, label: `Voir ${s.name}`, tone: 'ok' });
    }
  }
  if (!blocked && stages.length) {
    const winners = stages
      .filter((s) => s.ranking?.length)
      .map(
        (s) =>
          `${s.name} : ${s
            .ranking!.filter((r) => r.place === '1')
            .map((r) => r.team)
            .join(', ')}`,
      );
    items.push({ text: `Tournoi terminé : tous les matchs sont joués.${winners.length ? ` Vainqueurs - ${winners.join(' ; ')}.` : ''}`, tone: 'ok' });
  }
  return (
    <div className="space-y-2 border-l-2 border-red pl-4">
      <h3 className="text-xs font-semibold tracking-wide text-muted uppercase">À faire maintenant</h3>
      {items.map((i) => (
        <div key={i.text} className="flex flex-wrap items-center gap-3 text-sm">
          <span className={i.tone === 'ok' ? 'text-ok' : i.tone === 'pause' ? 'text-pause' : 'text-white'}>{i.text}</span>
          {i.to && (
            <Link to={i.to} className="border border-line-strong px-3 py-1 text-white hover:border-text">
              {i.label}
            </Link>
          )}
        </div>
      ))}
    </div>
  );
}

// --- Bracket drawn as a tree ------------------------------------------------------------------------------------

type BracketMatchView = OverviewStage['matches'][number];
const positionOf = (m: BracketMatchView) => Number(/#(\d+)$/.exec(m.label ?? '')?.[1] ?? 0);

/**
 * The bracket as a tree (asked by the user: easier to read than a list): one column per round, the upper bracket,
 * then the lower one, then the grand final. Matches are numbered (M1, M2…) and a team still unknown reads "Vainqueur
 * M3" / "Perdant M1". Clicking a match opens its line with every operation (launch, result, forfeit…).
 */
function BracketTree({
  stage: s,
  teams,
  servers,
  action,
  vetos,
}: {
  stage: OverviewStage;
  teams: TournamentTeam[];
  servers: ServerRow[];
  action: Action;
  vetos: Record<string, VetoLine>;
}) {
  const order = { UPPER: 0, LOWER: 1, FINAL: 2 } as Record<string, number>;
  const sorted = [...s.matches].sort(
    (a, b) => (order[a.bracket ?? ''] ?? 3) - (order[b.bracket ?? ''] ?? 3) || (a.round ?? 0) - (b.round ?? 0) || positionOf(a) - positionOf(b),
  );
  const number = new Map(sorted.map((m, i) => [m.label ?? m.id, i + 1]));
  const playable = sorted.find((m) => m.status === 'LIVE') ?? sorted.find((m) => m.status !== 'FINISHED' && m.homeId && m.awayId);
  const [selected, setSelected] = useState<string | null>(null);
  const current = sorted.find((m) => m.id === (selected ?? playable?.id)) ?? null;
  const duel = sorted.length === 1;

  /** "Vainq. H T1#1" → "Vainqueur M1" */
  const origin = (from?: string | null) => {
    if (!from) return 'à venir';
    const [what, ...label] = from.split(' ');
    const n = number.get(label.join(' '));
    return `${what.startsWith('Vainq') ? 'Vainqueur' : 'Perdant'} ${n ? `M${n}` : label.join(' ')}`;
  };
  /** the matches of the same bracket whose winner plays this one */
  const winnerSources = (m: BracketMatchView) =>
    [m.homeFrom, m.awayFrom].filter((f): f is string => !!f && f.startsWith('Vainq')).map((f) => f.split(' ').slice(1).join(' '));

  const columns = (bracket: string) => {
    const list = sorted.filter((m) => m.bracket === bracket);
    const rounds = [...new Set(list.map((m) => m.round ?? 1))].sort((a, b) => a - b);
    return rounds.map((r, i) => ({
      title: bracket === 'FINAL' ? (duel ? 'Finale' : '') : i === rounds.length - 1 ? `Finale du ${bracket === 'UPPER' ? 'haut' : 'bas'}` : `Tour ${i + 1}`,
      matches: list.filter((m) => (m.round ?? 1) === r),
    }));
  };
  const sections = duel
    ? [{ title: '', cols: columns('FINAL') }]
    : [
        { title: 'Bracket du haut', cols: columns('UPPER') },
        { title: 'Bracket du bas (une défaite)', cols: columns('LOWER') },
        { title: 'Grande finale', cols: columns('FINAL') },
      ];

  // Layout: first round stacked; a later match sits halfway between the matches that feed it (byes included)
  const W = 208; // card width (w-52)
  const H = 80; // card height (h-20)
  const GAP_X = 40;
  const GAP_Y = 16;
  const layout = (cols: { matches: BracketMatchView[] }[]) => {
    const center = new Map<string, number>();
    const column = new Map<string, number>();
    cols.forEach((col, ci) => {
      const wanted = col.matches.map((m, i) => {
        const from = winnerSources(m)
          .map((l) => center.get(l))
          .filter((y): y is number => y !== undefined);
        return { m, y: from.length ? from.reduce((a, b) => a + b, 0) / from.length : ci === 0 ? H / 2 + i * (H + GAP_Y) : NaN };
      });
      // no source in this bracket (seeded after a bye, or teams dropping from the upper bracket): next free place
      let floor = H / 2;
      for (const w of wanted) {
        const y = Number.isNaN(w.y) ? floor : Math.max(w.y, floor);
        center.set(w.m.label ?? w.m.id, y);
        column.set(w.m.label ?? w.m.id, ci);
        floor = y + H + GAP_Y;
      }
    });
    return { center, column, height: Math.max(H, ...[...center.values()].map((y) => y + H / 2)) };
  };

  const card = (m: BracketMatchView) => {
    const finished = m.status === 'FINISHED';
    const side = (name: string | null, from: string | null | undefined, score: number) => {
      const won = finished && !!name && m.winner === name;
      return (
        <div className={`flex items-center justify-between gap-2 px-2 py-1 ${won ? 'font-semibold text-white' : finished ? 'text-muted' : 'text-text'}`}>
          <span className={`truncate ${name ? '' : 'text-muted italic'}`}>{name ?? origin(from)}</span>
          {m.status !== 'PENDING' && <span className="font-mono tabular-nums">{score}</span>}
        </div>
      );
    };
    const tone = m.status === 'LIVE' ? 'border-ok' : current?.id === m.id ? 'border-text' : 'border-line-strong';
    return (
      <button
        type="button"
        onClick={() => setSelected(m.id)}
        className={`block h-20 w-52 overflow-hidden border bg-surface text-left text-sm hover:border-text ${tone}`}
        aria-pressed={current?.id === m.id}
      >
        <div className="flex justify-between gap-2 border-b border-line px-2 py-0.5 text-xs whitespace-nowrap text-muted">
          <span className="font-mono">M{number.get(m.label ?? m.id)}</span>
          <span title={m.advantageHome ? "Le vainqueur du haut commence avec 1 map d'avance" : undefined}>
            {m.format}
            {m.advantageHome ? ' +1 map' : ''}
            {m.isForfeit ? ' forfait' : m.status === 'LIVE' ? ' en cours' : finished ? ' fini' : ''}
          </span>
        </div>
        {side(m.home, m.homeFrom, m.scoreHome)}
        {side(m.away, m.awayFrom, m.scoreAway)}
      </button>
    );
  };

  const line = 'absolute border-line-strong';
  return (
    <div className="space-y-5">
      {sections
        .filter((sec) => sec.cols.length)
        .map((sec) => {
          const { center, column, height } = layout(sec.cols);
          const x = (ci: number) => ci * (W + GAP_X);
          const all = sec.cols.flatMap((c) => c.matches);
          return (
            <div key={sec.title} className="space-y-2">
              {sec.title && <h4 className="text-sm font-semibold text-text">{sec.title}</h4>}
              <div className="overflow-x-auto pb-2">
                <div className="relative" style={{ width: x(sec.cols.length - 1) + W, height: height + 20 }}>
                  {sec.cols.map((col, ci) => (
                    <div key={ci} className="absolute top-0 text-xs text-muted" style={{ left: x(ci) }}>
                      {col.title}
                    </div>
                  ))}
                  <div className="absolute inset-x-0 top-5 bottom-0">
                    {/* lines: from each feeding match to the middle of the gap, down / up, then into the match */}
                    {all.flatMap((m) => {
                      const key = m.label ?? m.id;
                      const ci = column.get(key)!;
                      const y = center.get(key)!;
                      const mid = x(ci) - GAP_X / 2;
                      const from = winnerSources(m).filter((l) => center.has(l));
                      if (!from.length) return [];
                      const ys = [y, ...from.map((l) => center.get(l)!)];
                      return [
                        <span key={`${key}-in`} aria-hidden className={`${line} border-t`} style={{ left: mid, top: y, width: GAP_X / 2 }} />,
                        <span
                          key={`${key}-v`}
                          aria-hidden
                          className={`${line} border-l`}
                          style={{ left: mid, top: Math.min(...ys), height: Math.max(...ys) - Math.min(...ys) }}
                        />,
                        ...from.map((l) => (
                          <span
                            key={`${key}-${l}`}
                            aria-hidden
                            className={`${line} border-t`}
                            style={{ left: x(column.get(l)!) + W, top: center.get(l)!, width: mid - x(column.get(l)!) - W }}
                          />
                        )),
                      ];
                    })}
                    {all.map((m) => (
                      <div key={m.id} className="absolute" style={{ left: x(column.get(m.label ?? m.id)!), top: center.get(m.label ?? m.id)! - H / 2 }}>
                        {card(m)}
                      </div>
                    ))}
                  </div>
                </div>
              </div>
            </div>
          );
        })}
      {current ? (
        <div className="space-y-1">
          <p className="text-xs text-muted">M{number.get(current.label ?? current.id)} (cliquez sur un autre match de l'arbre pour ses actions)</p>
          <ul className="border-y border-line">
            <MatchRow
              match={{
                ...current,
                label: `M${number.get(current.label ?? current.id)}`,
                homeFrom: origin(current.homeFrom),
                awayFrom: origin(current.awayFrom),
              }}
              servers={servers}
              teams={teams}
              action={action}
              veto={vetos[current.id]}
            />
          </ul>
        </div>
      ) : (
        <p className="text-sm text-muted">Cliquez sur un match de l'arbre pour ses actions.</p>
      )}
    </div>
  );
}
