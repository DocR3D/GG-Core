import { useEffect, useState, type FormEvent } from 'react';
import { Link, useNavigate, useParams } from 'react-router';
import { api, type OverviewStage, type ServerRow, type StandingRow, type TournamentTeam } from '../../lib/api';
import { Empty } from '../../components/live';
import { Button, Field, Input, Select, type Action } from '../../components/ui';
import { MatchRow } from './MatchRow';
import { isGenerated, isSettled, matchesLeft, range, stageMatches, tournamentPath, type VetoLine } from './model';

const TYPE: Record<string, string> = { ROUND_ROBIN: 'Poules', DOUBLE_ELIM: 'Double élimination' };

/**
 * Step "Phases": create the stages in their order (one by one - a "whole format at once" form was tried and found too
 * complex by the user), rename / retype / reset / delete them, generate the groups. A bracket after groups is
 * generated by their qualification.
 */
export function StagesSetup({
  tournamentId,
  stages,
  teams,
  action,
}: {
  tournamentId: string;
  stages: OverviewStage[];
  teams: TournamentTeam[];
  action: Action;
}) {
  const nextOrder = Math.max(0, ...stages.map((s) => s.order)) + 1;
  const hasGroups = stages.some((s) => s.type === 'ROUND_ROBIN');
  const hasBracket = stages.some((s) => s.type === 'DOUBLE_ELIM');
  return (
    <div className="space-y-8">
      <div className="flex flex-wrap items-end gap-4">
        <NewStage tournamentId={tournamentId} nextOrder={nextOrder} action={action} />
        {hasGroups && !hasBracket && (
          <Button
            disabled={action.busy}
            onClick={() =>
              action.run('Arbres Élite et Amateur créés', async () => {
                for (const [i, name] of ['Élite', 'Amateur'].entries()) {
                  await api(`/api/tournament/tournaments/${tournamentId}/stages`, {
                    method: 'POST',
                    body: JSON.stringify({ name, type: 'DOUBLE_ELIM', order: nextOrder + i }),
                  });
                }
                return true;
              })
            }
          >
            Créer les arbres Élite et Amateur
          </Button>
        )}
      </div>
      {stages.length === 0 && <Empty>Aucune phase. Un tournoi type : des poules, puis un arbre Élite et un arbre Amateur pour les qualifiés.</Empty>}
      {stages.map((s) => (
        <section key={s.id} className="space-y-3 border-t border-line pt-5">
          <StageHeader stage={s} />
          <StageEdit stage={s} action={action} />
          {isGenerated(s) ? (
            <p className="text-sm text-text">
              Générée : {stageMatches(s).length} matchs.{' '}
              <Link to={tournamentPath(tournamentId, `matchs/${s.id}`)} className="text-white underline">
                Voir les matchs de {s.name}
              </Link>
            </p>
          ) : (
            <GenerateOrWait stage={s} stages={stages} teams={teams} action={action} />
          )}
        </section>
      ))}
    </div>
  );
}

/** The group stage feeding a stage, if any (a bracket after groups gets its teams from the qualification). */
const feederOf = (s: OverviewStage, stages: OverviewStage[]) => stages.find((x) => x.type === 'ROUND_ROBIN' && x.order < s.order && x.id !== s.id) ?? null;

/**
 * A stage that follows groups waits for their qualification, which generates it; generating it before with picked
 * teams stays possible (the qualification then replaces it as long as nothing was played in it).
 */
function GenerateOrWait({ stage: s, stages, teams, action }: { stage: OverviewStage; stages: OverviewStage[]; teams: TournamentTeam[]; action: Action }) {
  const feeder = feederOf(s, stages);
  const [anyway, setAnyway] = useState(false);
  if (feeder && !s.participants?.length && !anyway) {
    return (
      <p className="text-sm text-text">
        Se génère tout seul à la qualification de {feeder.name} (onglet Qualification des matchs).{' '}
        <button type="button" className="text-muted underline hover:text-white" onClick={() => setAnyway(true)}>
          Générer quand même avec des équipes choisies
        </button>
      </p>
    );
  }
  return <Generate stage={s} teams={teams} action={action} />;
}

/** Rename, change the type (no match yet), reset the generation, delete - with a confirmation saying what is lost. */
function StageEdit({ stage: s, action }: { stage: OverviewStage; action: Action }) {
  const [mode, setMode] = useState<'rename' | 'reset' | 'delete' | null>(null);
  const [name, setName] = useState(s.name);
  const lost = stageMatches(s).filter((m) => m.status === 'FINISHED').length;
  const generated = isGenerated(s);
  const consequence = lost
    ? `Les résultats de ${lost} match${lost > 1 ? 's' : ''} fini${lost > 1 ? 's' : ''} seront perdus.`
    : "Aucun match fini : rien de joué n'est perdu.";
  if (mode === 'rename') {
    return (
      <form
        className="flex flex-wrap items-center gap-2"
        onSubmit={async (e: FormEvent) => {
          e.preventDefault();
          if (await action.run('Phase renommée', () => api(`/api/tournament/stages/${s.id}`, { method: 'PATCH', body: JSON.stringify({ name }) })))
            setMode(null);
        }}
      >
        <Input value={name} onChange={(e) => setName(e.target.value)} autoFocus />
        <Button small primary type="submit" disabled={action.busy || !name.trim()}>
          Renommer
        </Button>
        <Button small onClick={() => setMode(null)}>
          Annuler
        </Button>
      </form>
    );
  }
  if (mode === 'reset' || mode === 'delete') {
    return (
      <div className="flex flex-wrap items-center gap-2 border-l-2 border-red-light/60 pl-3 text-sm text-text">
        {mode === 'reset' ? `Réinitialiser ${s.name} : ses matchs et ses poules sont effacés, ses équipes restent.` : `Supprimer la phase ${s.name}.`}{' '}
        {consequence}
        <Button
          small
          danger
          disabled={action.busy}
          onClick={async () => {
            const ok =
              mode === 'reset'
                ? await action.run(`${s.name} réinitialisée`, () =>
                    api(`/api/tournament/stages/${s.id}/reset`, { method: 'POST', body: JSON.stringify({ force: true }) }),
                  )
                : await action.run(`${s.name} supprimée`, () => api(`/api/tournament/stages/${s.id}?force=true`, { method: 'DELETE' }));
            if (ok) setMode(null);
          }}
        >
          Confirmer
        </Button>
        <Button small onClick={() => setMode(null)}>
          Annuler
        </Button>
      </div>
    );
  }
  return (
    <div className="flex flex-wrap items-center gap-2">
      <Button small onClick={() => setMode('rename')}>
        Renommer
      </Button>
      {!generated && (
        <Select
          value={s.type}
          onChange={(e) =>
            action.run('Type changé', () => api(`/api/tournament/stages/${s.id}`, { method: 'PATCH', body: JSON.stringify({ type: e.target.value }) }))
          }
          className="text-xs"
          aria-label="Type de la phase"
        >
          <option value="ROUND_ROBIN">Poules</option>
          <option value="DOUBLE_ELIM">Double élimination</option>
        </Select>
      )}
      {generated && (
        <Button small danger onClick={() => setMode('reset')}>
          Réinitialiser
        </Button>
      )}
      <Button small danger onClick={() => setMode('delete')}>
        Supprimer
      </Button>
    </div>
  );
}

function StageHeader({ stage: s }: { stage: OverviewStage }) {
  const n = s.participants?.length ?? 0;
  return (
    <header className="flex flex-wrap items-baseline gap-3">
      <h3 className="text-lg font-semibold text-white">{s.name}</h3>
      <span className="text-sm text-muted">
        {s.type === 'DOUBLE_ELIM' && s.matches.length === 1 ? 'Finale' : (TYPE[s.type] ?? s.type)}, {n} équipe{n > 1 ? 's' : ''}
      </span>
    </header>
  );
}

function NewStage({ tournamentId, nextOrder, action }: { tournamentId: string; nextOrder: number; action: Action }) {
  const [name, setName] = useState('');
  const [type, setType] = useState('ROUND_ROBIN');
  return (
    <form
      className="flex flex-wrap items-end gap-2"
      onSubmit={async (e: FormEvent) => {
        e.preventDefault();
        const ok = await action.run(`Phase ${name.trim()} créée`, () =>
          api(`/api/tournament/tournaments/${tournamentId}/stages`, { method: 'POST', body: JSON.stringify({ name: name.trim(), type, order: nextOrder }) }),
        );
        if (ok) setName('');
      }}
    >
      <Field label="Nouvelle phase">
        <Input value={name} onChange={(e) => setName(e.target.value)} placeholder="Poules, Élite, Amateur…" />
      </Field>
      <Field label="Type">
        <Select value={type} onChange={(e) => setType(e.target.value)}>
          <option value="ROUND_ROBIN">Poules</option>
          <option value="DOUBLE_ELIM">Double élimination</option>
        </Select>
      </Field>
      <Button type="submit" disabled={action.busy || !name.trim()}>
        Créer la phase
      </Button>
    </form>
  );
}

/**
 * Step "Matchs", one stage: groups round by round with their standings and the qualification, or the bracket;
 * every match with its operations; a format for the whole stage or one bracket. Not generated yet: generated here.
 */
export function StagePlay({
  stage: s,
  stages,
  teams,
  servers,
  action,
  vetos,
}: {
  stage: OverviewStage;
  stages: OverviewStage[];
  teams: TournamentTeam[];
  servers: ServerRow[];
  action: Action;
  vetos: Record<string, VetoLine>;
}) {
  const generated = isGenerated(s);
  return (
    <section className="space-y-4">
      <StageHeader stage={s} />

      {!generated && <GenerateOrWait stage={s} stages={stages} teams={teams} action={action} />}

      {s.type === 'ROUND_ROBIN' && s.groups.length > 0 && (
        <>
          <div className="flex flex-wrap gap-x-10 gap-y-4">
            {s.groups.map((g) => (
              <div key={g.id ?? g.name} className="space-y-1">
                <h4 className="text-sm font-semibold text-text">Poule {g.name}</h4>
                <Standings rows={g.standings} />
              </div>
            ))}
          </div>
          <Rounds stage={s} teams={teams} servers={servers} action={action} vetos={vetos} />
          <CloseGroups stage={s} action={action} />
        </>
      )}

      {s.type === 'DOUBLE_ELIM' && s.matches.length > 0 && <BracketTree stage={s} teams={teams} servers={servers} action={action} vetos={vetos} />}

      {s.ranking && s.ranking.length > 0 && <p className="text-sm text-text">Classement : {s.ranking.map((r) => `${r.place}. ${r.team}`).join(', ')}</p>}

      {generated && <StageFormat stage={s} action={action} />}
    </section>
  );
}

/** Ends the groups early (no time left): the matches not played are cancelled, the standings count the others. */
function CloseGroups({ stage: s, action }: { stage: OverviewStage; action: Action }) {
  const [confirm, setConfirm] = useState(false);
  const left = matchesLeft(s);
  if (!left) return null;
  return confirm ? (
    <div className="flex flex-wrap items-center gap-2 border-l-2 border-red-light/60 pl-3 text-sm text-text">
      Clore les poules : les {left} match{left > 1 ? 's' : ''} pas encore joué{left > 1 ? 's' : ''} sont annulés, le classement se fait sur les matchs joués. Un
      game en cours doit d'abord finir.
      <Button
        small
        danger
        disabled={action.busy}
        onClick={async () => {
          if (await action.run('Poules closes', () => api(`/api/tournament/stages/${s.id}/close-groups`, { method: 'POST' }))) setConfirm(false);
        }}
      >
        Clore les poules
      </Button>
      <Button small onClick={() => setConfirm(false)}>
        Annuler
      </Button>
    </div>
  ) : (
    <Button small danger onClick={() => setConfirm(true)}>
      Clore les poules maintenant ({left} match{left > 1 ? 's' : ''} à jouer)
    </Button>
  );
}

/**
 * Tab "Qualification" (after the groups, its own screen - asked by the user): the final standings, the matches
 * still to play (close the groups to go on), then the rules sending the ranks to the next stages.
 */
export function QualifyStep({ stage: s, stages, action }: { stage: OverviewStage; stages: OverviewStage[]; action: Action }) {
  const left = matchesLeft(s);
  return (
    <section className="space-y-5">
      <header className="flex flex-wrap items-baseline gap-3">
        <h3 className="text-lg font-semibold text-white">Qualification de {s.name}</h3>
        <span className={`text-sm ${left ? 'text-pause' : 'text-ok'}`}>{left ? `${left} match${left > 1 ? 's' : ''} encore à jouer` : 'poules finies'}</span>
      </header>
      <div className="flex flex-wrap gap-x-10 gap-y-4">
        {s.groups.map((g) => (
          <div key={g.id ?? g.name} className="space-y-1">
            <h4 className="text-sm font-semibold text-text">Poule {g.name}</h4>
            <Standings rows={g.standings} />
          </div>
        ))}
      </div>
      <TieRules />
      {left > 0 && <CloseGroups stage={s} action={action} />}
      <Qualify stage={s} stages={stages} action={action} />
    </section>
  );
}

function TieRules() {
  return (
    <p className="max-w-prose text-sm text-muted">
      Départage : points (victoire 3, nul 1), puis les matchs entre les équipes à égalité, puis la différence de rounds, puis les rounds gagnés. « Égalité à
      trancher » : tout est encore égal, l'ordre se choisit à la qualification.
    </p>
  );
}

/** Groups or bracket from the teams qualified into the stage, or from teams picked here (their order = the seeds). */
function Generate({ stage: s, teams, action }: { stage: OverviewStage; teams: TournamentTeam[]; action: Action }) {
  const qualified = s.participants ?? [];
  const [picked, setPicked] = useState<string[]>(() => (qualified.length ? [] : teams.map((t) => t.id)));
  // the teams arrive after the first render: start from all of them, in their order
  useEffect(() => {
    if (!qualified.length && teams.length) setPicked((p) => (p.length ? p : teams.map((t) => t.id)));
  }, [teams, qualified.length]);
  const [groupCount, setGroupCount] = useState('2');
  const [format, setFormat] = useState('BO1');
  const [formats, setFormats] = useState({ upper: 'BO1', lower: 'BO1', grandFinal: 'BO3' });
  const useQualified = qualified.length > 0;
  const count = useQualified ? qualified.length : picked.length;
  const rr = s.type === 'ROUND_ROBIN';
  const groups = Number(groupCount) || 0;
  const tooManyGroups = rr && groups > 0 && count < groups * 2;
  return (
    <form
      className="space-y-3"
      onSubmit={(e: FormEvent) => {
        e.preventDefault();
        const teamIds = useQualified ? undefined : picked;
        action.run(rr ? 'Poules générées' : 'Arbre généré', () =>
          rr
            ? api(`/api/tournament/stages/${s.id}/groups/generate`, {
                method: 'POST',
                body: JSON.stringify({ teamIds, groupCount: Number(groupCount), format }),
              })
            : api(`/api/tournament/stages/${s.id}/bracket/generate`, { method: 'POST', body: JSON.stringify({ teamIds, formats }) }),
        );
      }}
    >
      {useQualified ? (
        <p className="text-sm text-text">
          {qualified.length} équipes qualifiées, dans l'ordre des seeds :{' '}
          {[...qualified]
            .sort((a, b) => a.seed - b.seed)
            .map((q) => q.name)
            .join(', ')}
          .
        </p>
      ) : (
        <SeedPicker teams={teams} picked={picked} onChange={setPicked} />
      )}
      <div className="flex flex-wrap items-end gap-2">
        {rr ? (
          <>
            <Field label="Nombre de poules">
              <Input inputMode="numeric" value={groupCount} onChange={(e) => setGroupCount(e.target.value.replace(/\D/g, ''))} className="w-20 font-mono" />
            </Field>
            <Field label="Format des matchs">
              <FormatSelect value={format} onChange={setFormat} />
            </Field>
          </>
        ) : (
          <>
            <Field label="Bracket du haut">
              <FormatSelect value={formats.upper} onChange={(v) => setFormats({ ...formats, upper: v })} />
            </Field>
            <Field label="Bracket du bas">
              <FormatSelect value={formats.lower} onChange={(v) => setFormats({ ...formats, lower: v })} />
            </Field>
            <Field label="Grande finale">
              <FormatSelect value={formats.grandFinal} onChange={(v) => setFormats({ ...formats, grandFinal: v })} noBo1={count > 2} />
            </Field>
          </>
        )}
        {tooManyGroups && (
          <p className="w-full text-sm text-red-light">
            {count} équipes pour {groups} poules : il faut au moins 2 équipes par poule (au plus {Math.floor(count / 2)} poules).
          </p>
        )}
        <Button primary type="submit" disabled={action.busy || count < 2 || (rr && !groups) || tooManyGroups}>
          {rr ? 'Générer les poules' : "Générer l'arbre"}
        </Button>
      </div>
    </form>
  );
}

/** The teams of a stage in seed order: first = best seed. */
function SeedPicker({ teams, picked, onChange }: { teams: TournamentTeam[]; picked: string[]; onChange: (ids: string[]) => void }) {
  const name = (id: string) => teams.find((t) => t.id === id)?.name ?? id;
  const others = teams.filter((t) => !picked.includes(t.id));
  const move = (i: number) => {
    const next = [...picked];
    [next[i - 1], next[i]] = [next[i], next[i - 1]];
    onChange(next);
  };
  return (
    <div className="space-y-2">
      <p className="text-sm text-muted">Équipes, dans l'ordre des seeds (la première est la tête de série) :</p>
      <ol className="space-y-1">
        {picked.map((id, i) => (
          <li key={id} className="flex items-center gap-2 text-sm">
            <span className="w-6 text-right font-mono text-muted">{i + 1}</span>
            <span className="min-w-40 text-white">{name(id)}</span>
            <Button small disabled={i === 0} onClick={() => move(i)}>
              Monter
            </Button>
            <Button small onClick={() => onChange(picked.filter((x) => x !== id))}>
              Retirer
            </Button>
          </li>
        ))}
      </ol>
      {others.length > 0 && (
        <Select value="" onChange={(e) => e.target.value && onChange([...picked, e.target.value])} className="text-sm" aria-label="Ajouter une équipe">
          <option value="">Ajouter une équipe</option>
          {others.map((t) => (
            <option key={t.id} value={t.id}>
              {t.name}
            </option>
          ))}
        </Select>
      )}
    </div>
  );
}

/**
 * The group matches round by round (decided with the user): the round being played is unfolded, finished and
 * coming rounds are folded with a summary. A coming round's veto opens when the previous rounds are finished, or
 * earlier with "Ouvrir les vétos du tour N". Launching a game is never blocked by its round.
 */
function Rounds({
  stage: s,
  teams,
  servers,
  action,
  vetos,
}: {
  stage: OverviewStage;
  teams: TournamentTeam[];
  servers: ServerRow[];
  action: Action;
  vetos: Record<string, VetoLine>;
}) {
  const all = s.groups.flatMap((g) => g.matches.map((m) => ({ m, group: `Poule ${g.name}` })));
  const rounds = [...new Set(all.map((x) => x.m.round ?? 1))].sort((a, b) => a - b);
  const current = rounds.find((r) => all.some((x) => (x.m.round ?? 1) === r && !isSettled(x.m))) ?? null;
  // folded / unfolded by the admin; by default only the round being played is unfolded
  const [unfolded, setUnfolded] = useState<Record<number, boolean>>({});
  return (
    <div className="space-y-3">
      {rounds.map((r) => {
        const list = all.filter((x) => (x.m.round ?? 1) === r);
        const done = list.filter((x) => isSettled(x.m)).length;
        const state = done === list.length ? 'terminé' : r === current ? 'en cours' : 'à venir';
        const open = unfolded[r] ?? r === current;
        return (
          <div key={r} className={r === current ? 'border-l-2 border-ok pl-3' : 'border-l-2 border-line pl-3'}>
            <div className="flex flex-wrap items-center gap-3">
              <button
                type="button"
                className="text-left font-semibold text-white hover:underline"
                onClick={() => setUnfolded({ ...unfolded, [r]: !open })}
                aria-expanded={open}
              >
                Tour {r}
              </button>
              <span className={`text-sm ${state === 'en cours' ? 'text-ok' : 'text-muted'}`}>
                {state}, {done}/{list.length} joués
              </span>
              {current !== null && r > current && (
                <Button
                  small
                  disabled={action.busy}
                  onClick={() =>
                    action.run(`Vétos du tour ${r} ouverts`, () => api(`/api/tournament/stages/${s.id}/rounds/${r}/open-veto`, { method: 'POST' }))
                  }
                >
                  Ouvrir les vétos du tour {r}
                </Button>
              )}
            </div>
            {open && (
              <ul className="mt-2 divide-y divide-line border-y border-line">
                {list.map((x) => (
                  <MatchRow key={x.m.id} match={x.m} tag={x.group} servers={servers} teams={teams} action={action} veto={vetos[x.m.id]} />
                ))}
              </ul>
            )}
          </div>
        );
      })}
    </div>
  );
}

